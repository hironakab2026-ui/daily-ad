// mets（METs値）の出典：
//   「改訂第2版 身体活動のメッツ(METs)表 成人版」（医薬基盤・健康・栄養研究所、2024年）
//   https://www.nibn.go.jp/activities/documents/2024Compendium_table_adult_ver1_1_5.pdf
//   （原典: Compendium of Physical Activities, 2011年版に準拠）
//   種目名そのものずばりの項目はないため、最も近いカテゴリの値を採用している。
//   対応関係（メッツ表のコード）：
//     5.0 = 02052 Resistance (weight) training, squats, deadlift, slow or explosive effort
//           → フリーウェイトの複合種目（ベンチプレス・スクワット・デッドリフト）
//     3.5 = 02054 Resistance (weight) training, multiple exercises, 8-15 reps at varied resistance
//           → マシン・補助的な種目（ラットプルダウン・レッグプレス・単関節種目）
//     3.0 = 02056 Body weight resistance exercises (squat, lunge, push-up, crunch), general
//           → 自重の複合種目（腕立て伏せ・ランジ）
//     3.8 = 02022 Calisthenics (pushups, sit ups, pull-ups, lunges), moderate effort
//           → 懸垂
//     2.8 = 02024 Calisthenics (curl ups, abdominal crunches, plank), light effort
//           → 体幹・腹筋系（クランチ・プランク）
//
// 消費カロリーの推定式（同資料の冒頭に掲載の簡易式をそのまま採用）：
//   消費カロリー(kcal) = メッツ × 体重(kg) × 運動時間(h)
//   このアプリでは1セットあたりの実施時間を記録していないため、
//   「1セット ≒ 1分」という簡易な仮定をおいて計算する（public/app.js の estimateKcal を参照）。
//   あくまで目安であり、正確な消費量を保証するものではない。
//
